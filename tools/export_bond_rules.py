"""Export pymatgen's bonding rule (JmolNN) as data the browser can use: web/addons/bond_rules.js.

    uv run tools/export_bond_rules.py

pymatgen's JmolNN calls two atoms bonded when  min_bond_distance < d <= r_a + r_b + tol,  with one radius per
element (pymatgen/core/bonds_jmol_ob.yaml, Jmol's table taken from OpenBabel) and tol = 0.45 Å,
min_bond_distance = 0.4 Å (the defaults of JmolNN). This script copies those numbers out unchanged, so the
slides use pymatgen's rule without needing Python at show time. Re-run it after upgrading pymatgen; the
header of the generated file records the version.
"""

import inspect
import json
from importlib.metadata import version
from pathlib import Path

import yaml
from pymatgen.analysis.local_env import JmolNN
from pymatgen.core import bonds

OUT = Path(__file__).resolve().parent.parent / "web" / "addons" / "bond_rules.js"


def main() -> None:
    params = inspect.signature(JmolNN.__init__).parameters
    tol, min_d = params["tol"].default, params["min_bond_distance"].default
    radii = yaml.safe_load((Path(bonds.__file__).parent / "bonds_jmol_ob.yaml").read_text(encoding="utf-8"))
    rules = {"tol": tol, "min": min_d, "radii": {el: float(r) for el, r in sorted(radii.items())}}
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(
            f"// Generated by tools/export_bond_rules.py from pymatgen {version('pymatgen')} (JmolNN): do not edit by hand.\n"
            "// Two atoms are bonded when  min < distance <= radii[a] + radii[b] + tol  (Å). Used by web/addons/crystal.js.\n"
            "//\n"
            "//   Deck.bondRules = { tol, min, radii: { Ti: 1.47, O: 0.68, ... } }   // Å; one radius per element (Jmol's table)\n"
            "//   Load it before crystal_logic.js. Re-run `uv run tools/export_bond_rules.py` after upgrading pymatgen.\n"
            f"window.Deck = window.Deck || {{}};\nwindow.Deck.bondRules = {json.dumps(rules)};\n"
        )
    print(f"{OUT}: {len(rules['radii'])} elements, tol={tol}, min={min_d}")


if __name__ == "__main__":
    main()
