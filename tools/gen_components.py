#!/usr/bin/env python3
"""Write docs/components.md from the header comment of every component in web/.

A component's header is the run of `//` lines at the top of each file in web/*.js and web/addons/*.js. It is the
component's documentation: edit it in the source file, then run this script.

    python tools/gen_components.py           # write docs/components.md
    python tools/gen_components.py --check   # exit 1 (and say what differs) if docs/components.md is stale

tools/check_docs.py runs the same --check. Standard library only; output is deterministic (no timestamps).
"""
from __future__ import annotations

import argparse
import difflib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "components.md"
GENERATED_LINE = (
    "Generated by tools/gen_components.py from the header comment of each file in web/. "
    "Do not edit by hand; edit the header comment in the source file and re-run."
)


def rel(path: Path, root: Path = ROOT) -> str:
    return path.relative_to(root).as_posix()


def source_files(root: Path = ROOT) -> list[Path]:
    """web/*.js in name order, then web/addons/*.js in name order. Nothing is skipped."""
    top = sorted((root / "web").glob("*.js"), key=lambda p: p.name)
    addons = sorted((root / "web" / "addons").glob("*.js"), key=lambda p: p.name)
    return top + addons


def header_lines(path: Path) -> list[str]:
    """The leading run of `//` lines with the marker removed; blank `//` lines stay blank.

    Leading and trailing blank lines are dropped; blank lines inside the header are kept.
    """
    text = path.read_text(encoding="utf-8-sig")  # universal newlines: CRLF files read as LF
    lines: list[str] = []
    for raw in text.split("\n"):
        line = raw.rstrip()
        if not line.startswith("//"):
            break
        body = line[2:]
        if body.startswith(" "):
            body = body[1:]
        lines.append(body)
    while lines and not lines[0].strip():
        lines.pop(0)
    while lines and not lines[-1].strip():
        lines.pop()
    return lines


def summary(lines: list[str]) -> str:
    """The first non-empty header line: the component's one-line summary."""
    return lines[0].strip() if lines else ""


def anchor(title: str) -> str:
    """GitHub's heading anchor for a `## title` heading."""
    kept = [c for c in title.lower() if c.isalnum() or c in "-_ "]
    return "".join(kept).replace(" ", "-")


def _fence(body: str) -> str:
    fence = "```"
    while fence in body:
        fence += "`"
    return fence


def render(root: Path = ROOT) -> str:
    entries = [(rel(p, root), header_lines(p)) for p in source_files(root)]
    out = [
        GENERATED_LINE,
        "",
        "# Components",
        "",
        "The API of each component in `web/`, as its header comment states it. Edit the comment in the source file, "
        "not here.",
        "",
        "## Contents",
        "",
        "| File | Summary |",
        "| --- | --- |",
    ]
    for name, hdr in entries:
        cell = summary(hdr).replace("|", "\\|")
        out.append(f"| [{name}](#{anchor(name)}) | {cell} |")
    out.append("")
    for name, hdr in entries:
        out += [f"## {name}", ""]
        if hdr:
            body = "\n".join(hdr)
            fence = _fence(body)
            out += [fence + "text", body, fence]
        else:
            out.append("_No header comment._")
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def _section(text: str, name: str):
    head = f"## {name}\n"
    start = text.find(head)
    if start < 0:
        return None
    end = text.find("\n## ", start + len(head))
    return text[start:] if end < 0 else text[start : end + 1]


def check(root: Path = ROOT) -> tuple[bool, str]:
    """Compare docs/components.md with a fresh render. Returns (ok, message)."""
    doc = root / "docs" / "components.md"
    expected = render(root)
    if not doc.is_file():
        return False, f"{rel(doc, root)} is missing: run python tools/gen_components.py"
    actual = doc.read_text(encoding="utf-8").replace("\r\n", "\n")
    if actual == expected:
        return True, f"{rel(doc, root)} is up to date"
    differing = [
        rel(p, root) for p in source_files(root)
        if _section(actual, rel(p, root)) != _section(expected, rel(p, root))
    ]
    lines = [f"{rel(doc, root)} is out of date."]
    if differing:
        lines.append("sections that differ: " + ", ".join(differing))
    else:
        lines.append("the contents table or the preamble differs")
    diff = list(difflib.unified_diff(actual.splitlines(), expected.splitlines(),
                                     "docs/components.md (committed)", "generated", n=1, lineterm=""))
    lines += diff[:40]
    if len(diff) > 40:
        lines.append(f"... {len(diff) - 40} more diff lines")
    lines.append("run: python tools/gen_components.py")
    return False, "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    parser = argparse.ArgumentParser(description="Generate docs/components.md from web/ header comments.")
    parser.add_argument("--check", action="store_true",
                        help="do not write; exit 1 if docs/components.md is out of date")
    args = parser.parse_args(argv)
    if args.check:
        ok, message = check()
        print(message)
        return 0 if ok else 1
    DOC.parent.mkdir(parents=True, exist_ok=True)
    with open(DOC, "w", encoding="utf-8", newline="\n") as f:
        f.write(render())
    print(f"wrote {rel(DOC)} ({len(source_files())} components)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
